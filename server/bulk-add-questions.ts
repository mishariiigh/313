export async function bulkAddQuestions() {
  try {
    console.log("🔄 Starting bulk question addition...");
    
    // Get all categories
    const categories = await storage.getAllCategories();
    console.log(`📊 Found ${categories.length} categories`);
    
    let totalAdded = 0;
    
    for (const category of categories) {
      const categoryName = category.name;
      const templates = questionTemplates[categoryName as keyof typeof questionTemplates];
      
      if (!templates) {
        console.log(`⚠️  No templates found for category: ${categoryName}`);
        continue;
      }
      
      console.log(`📝 Adding questions for: ${category.displayName}`);
      
      // Add questions for each difficulty
      for (const difficulty of ['سهل', 'متوسط', 'صعب']) {
        const difficultyKey = difficulty === 'سهل' ? 'easy' : difficulty === 'متوسط' ? 'medium' : 'hard';
        const questionsForDifficulty = templates[difficultyKey] || [];
        
        for (let i = 0; i < Math.min(17, questionsForDifficulty.length); i++) {
          const template = questionsForDifficulty[i];
          
          try {
            const questionData = {
              question: template.q,
              answer: template.a,
              category: categoryName,
              difficulty: difficulty,
              hint: template.h,
              explanation: "",
              imageUrl: "",
              isActive: true
            };
            
            await storage.createQuestion(questionData);
            totalAdded++;
            
            if (totalAdded % 10 === 0) {
              console.log(`✅ Added ${totalAdded} questions...`);
            }
            
          } catch (error: any) {
            console.error(`❌ Failed to add question: ${template.q}`, error.message);
          }
        }
      }
    }
    
    console.log(`✅ Bulk question addition completed! Added ${totalAdded} questions total`);
    return { success: true, totalAdded };
    
  } catch (error: any) {
    console.error("❌ Error during bulk question addition:", error);
    return { success: false, error: error.message };
  }
}